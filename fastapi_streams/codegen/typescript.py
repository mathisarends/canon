import json
import re
from importlib.resources import files

from fastapi_streams.codegen.ir import (
    Array,
    Contract,
    Intersection,
    LiteralType,
    Object,
    Operation,
    Reference,
    Scalar,
    Type,
    Union,
)
from fastapi_streams.codegen.names import identifier
from fastapi_streams.codegen.templating import add_filters, environment

_HEADER = "// Generated by fastapi-streams. Do not edit.\n"
_JSON = (
    "export type JsonValue = string | number | boolean | null "
    "| JsonValue[] | { [key: string]: JsonValue };"
)


def render_type(type_: Type, prefix: str = "") -> str:
    match type_:
        case Scalar(name="JsonValue"):
            return prefix + "JsonValue"
        case Scalar(name="integer"):
            return "number"
        case Scalar(name=name):
            return name
        case LiteralType(value=value):
            return json.dumps(value, ensure_ascii=False)
        case Reference(name=name):
            return prefix + name
        case Array(item=item):
            return f"Array<{render_type(item, prefix=prefix)}>"
        case Union(members=members):
            return (
                "("
                + " | ".join(render_type(part, prefix=prefix) for part in members)
                + ")"
            )
        case Intersection(members=members):
            return (
                "("
                + " & ".join(render_type(part, prefix=prefix) for part in members)
                + ")"
            )
        case Object(fields=fields, additional=additional):
            parts = [
                f"{json.dumps(field.name)}{'' if field.required else '?'}: "
                f"{render_type(field.type, prefix=prefix)};"
                for field in fields
            ]
            if additional is not None:
                values = {render_type(additional, prefix=prefix)}
                values.update(
                    render_type(field.type, prefix=prefix) for field in fields
                )
                if any(not field.required for field in fields):
                    values.add("undefined")
                parts.append(f"[key: string]: {' | '.join(sorted(values))};")
            # An empty model is a JSON object, not TypeScript's non-nullish {} type.
            return (
                "{\n" + "\n".join("  " + part for part in parts) + "\n}"
                if parts
                else "{ [key: string]: never }"
            )


def _input_name(operation: Operation) -> str:
    return identifier(operation.operation_id, upper=True) + "Params"


def _path(operation: Operation) -> str:
    parts: list[str] = []
    cursor = 0
    by_name = {param.name: param.argument for param in operation.parameters}
    for match in re.finditer(r"\{([^{}]+)\}", operation.path):
        parts.append(json.dumps(operation.path[cursor : match.start()]))
        parts.append(f"encodePath(input.{by_name[match[1]]})")
        cursor = match.end()
    parts.append(json.dumps(operation.path[cursor:]))
    return " + ".join(parts)


def _required(operation: Operation) -> bool:
    return any(param.required for param in operation.parameters) or (
        operation.body is not None and operation.body.required
    )


def _error_type(operation: Operation) -> str:
    return " | ".join(
        sorted({render_type(error.type, prefix="Types.") for error in operation.errors})
    )


def generate_typescript(contract: Contract) -> dict[str, str]:
    env = environment()

    def pascal(value: str) -> str:
        return identifier(value, upper=True)

    add_filters(
        env,
        ts_type=render_type,
        json=json.dumps,
        pascal=pascal,
        input_name=_input_name,
        required=_required,
        error_type=_error_type,
        path=_path,
    )
    output: dict[str, str] = {}
    declarations = [
        f"export type {declaration.name} = {render_type(declaration.type)};"
        for declaration in contract.declarations
    ]
    output["types.ts"] = "\n".join([_HEADER, _JSON, "", *declarations]) + "\n"
    for template in ("sse.ts", "errors.ts"):
        output[f"transport/{template}"] = (
            files(__package__)
            .joinpath(f"templates/{template}")
            .read_text(encoding="utf-8")
        )
    grouped: dict[str, list[Operation]] = {}
    for operation in contract.operations:
        grouped.setdefault(operation.group, []).append(operation)
    groups: list[dict[str, str]] = []
    exports = [
        _HEADER,
        'export { createClient } from "./client.js";',
        'export type * from "./types.js";',
        'export type { ClientOptions, RequestOptions } from "./transport/sse.js";',
        "export { HttpError, TransportError, StreamParseError } "
        'from "./transport/errors.js";',
    ]
    for group, operations in sorted(grouped.items()):
        operations.sort(key=lambda operation: operation.name)
        directory = operations[0].directory
        factory = "create" + group[:1].upper() + group[1:] + "Api"
        groups.append(dict(name=group, factory=factory, directory=directory))
        functions = ["stream"]
        if any(
            param.location == "path" for op in operations for param in op.parameters
        ):
            functions.append("encodePath")
        if any(
            param.location == "query" for op in operations for param in op.parameters
        ):
            functions.append("appendQuery")
        if any(
            param.location == "header" for op in operations for param in op.parameters
        ):
            functions.append("setHeader")
        output[f"{directory}/api.ts"] = env.get_template("typescript/api.ts.j2").render(
            operations=operations,
            functions=functions,
            factory=factory,
        )
        output[f"{directory}/index.ts"] = _HEADER + 'export * from "./api.js";\n'
        exports.append(f'export type * from "./{directory}/api.js";')
    output["client.ts"] = env.get_template("typescript/client.ts.j2").render(
        groups=groups
    )
    output["index.ts"] = "\n".join(exports) + "\n"
    return output
