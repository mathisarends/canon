import json
import re
from importlib.resources import files

from fastapi_streams.codegen.ir import (
    Array,
    Contract,
    Intersection,
    LiteralType,
    Object,
    Operation,
    Reference,
    Scalar,
    Type,
    Union,
)
from fastapi_streams.codegen.names import identifier

_HEADER = "// Generated by fastapi-streams. Do not edit.\n"
_JSON = (
    "export type JsonValue = string | number | boolean | null "
    "| JsonValue[] | { [key: string]: JsonValue };"
)


def render_type(type_: Type, *, prefix: str = "") -> str:
    match type_:
        case Scalar(name="JsonValue"):
            return prefix + "JsonValue"
        case Scalar(name=name):
            return name
        case LiteralType(value=value):
            return json.dumps(value, ensure_ascii=False)
        case Reference(name=name):
            return prefix + name
        case Array(item=item):
            return f"Array<{render_type(item, prefix=prefix)}>"
        case Union(members=members):
            return (
                "("
                + " | ".join(render_type(part, prefix=prefix) for part in members)
                + ")"
            )
        case Intersection(members=members):
            return (
                "("
                + " & ".join(render_type(part, prefix=prefix) for part in members)
                + ")"
            )
        case Object(fields=fields, additional=additional):
            parts = [
                f"{json.dumps(field.name)}{'' if field.required else '?'}: "
                f"{render_type(field.type, prefix=prefix)};"
                for field in fields
            ]
            if additional is not None:
                values = {render_type(additional, prefix=prefix)}
                values.update(
                    render_type(field.type, prefix=prefix) for field in fields
                )
                if any(not field.required for field in fields):
                    values.add("undefined")
                parts.append(f"[key: string]: {' | '.join(sorted(values))};")
            # An empty model is a JSON object, not TypeScript's non-nullish {} type.
            return (
                "{\n" + "\n".join("  " + part for part in parts) + "\n}"
                if parts
                else "{ [key: string]: never }"
            )


def _input_name(operation: Operation) -> str:
    return identifier(operation.operation_id, upper=True) + "Params"


def _path(operation: Operation) -> str:
    parts: list[str] = []
    cursor = 0
    by_name = {param.name: param.argument for param in operation.parameters}
    for match in re.finditer(r"\{([^{}]+)\}", operation.path):
        parts.append(json.dumps(operation.path[cursor : match.start()]))
        parts.append(f"encodePath(input.{by_name[match[1]]})")
        cursor = match.end()
    parts.append(json.dumps(operation.path[cursor:]))
    return " + ".join(parts)


def _operation(operation: Operation) -> tuple[str, str]:
    params = [
        f"  {param.argument}{'' if param.required else '?'}: "
        f"{render_type(param.type, prefix='Types.')};"
        for param in operation.parameters
    ]
    if operation.body:
        params.append(
            f"  body{'' if operation.body.required else '?'}: "
            f"{render_type(operation.body.type, prefix='Types.')};"
        )
    declaration = ""
    if params:
        declaration = (
            f"export interface {_input_name(operation)} {{\n"
            + "\n".join(params)
            + "\n}\n"
        )
    if operation.errors:
        errors = " | ".join(
            sorted(
                {render_type(error.type, prefix="Types.") for error in operation.errors}
            )
        )
        error_name = identifier(operation.operation_id, upper=True) + "Error"
        declaration += f"export type {error_name} = {errors};\n"
    required = any(param.required for param in operation.parameters) or (
        operation.body is not None and operation.body.required
    )
    signature = (
        f"input: {_input_name(operation)}{'' if required else ' = {}'}, "
        if params
        else ""
    )
    lines = [
        f"    {operation.name}(\n      {signature}options: RequestOptions = {{}}\n"
        f"    ): AsyncIterable<{render_type(operation.event, prefix='Types.')}> {{",
        "      const query = new URLSearchParams();",
        "      const headers = new Headers();",
    ]
    for param in operation.parameters:
        if param.location == "query":
            lines.append(
                f"      appendQuery(query, {json.dumps(param.name)}, "
                f"input.{param.argument}, {str(param.explode).lower()});"
            )
        elif param.location == "header":
            lines.append(
                f"      setHeader(headers, {json.dumps(param.name)}, "
                f"input.{param.argument});"
            )
    lines += [
        f"      return stream<{render_type(operation.event, prefix='Types.')}>("
        "client, {",
        f"        path: {_path(operation)},",
        f"        method: {json.dumps(operation.method)},",
        "        query,",
        "        headers,",
    ]
    if operation.body:
        lines.append(
            "        ...(input.body === undefined ? {} : "
            "{ body: JSON.stringify(input.body) }),"
        )
    lines += ["      }, options);", "    },"]
    return declaration, "\n".join(lines)


def generate_typescript(contract: Contract) -> dict[str, str]:
    output: dict[str, str] = {}
    types = [_HEADER, _JSON, ""]
    types.extend(
        f"export type {declaration.name} = {render_type(declaration.type)};"
        for declaration in contract.declarations
    )
    output["types.ts"] = "\n".join(types) + "\n"
    for template in ("sse.ts", "errors.ts"):
        output[f"transport/{template}"] = (
            files(__package__)
            .joinpath(f"templates/{template}")
            .read_text(encoding="utf-8")
        )
    grouped: dict[str, list[Operation]] = {}
    for operation in contract.operations:
        grouped.setdefault(operation.group, []).append(operation)
    imports = [_HEADER, 'import type { ClientOptions } from "./transport/sse.js";']
    groups: list[str] = []
    exports = [
        _HEADER,
        'export { createClient } from "./client.js";',
        'export type * from "./types.js";',
        'export type { ClientOptions, RequestOptions } from "./transport/sse.js";',
        "export { HttpError, TransportError, StreamParseError } "
        'from "./transport/errors.js";',
    ]
    for group, operations in sorted(grouped.items()):
        operations.sort(key=lambda operation: operation.name)
        directory = operations[0].directory
        factory = "create" + group[:1].upper() + group[1:] + "Api"
        imports.append(f'import {{ {factory} }} from "./{directory}/api.js";')
        groups.append(f"    {group}: {factory}(options),")
        declarations: list[str] = []
        methods: list[str] = []
        for operation in operations:
            declaration, method = _operation(operation)
            declarations.append(declaration)
            methods.append(method)
        used = "\n".join(methods)
        functions = ["stream"] + [
            name
            for name in ("appendQuery", "encodePath", "setHeader")
            if name + "(" in used
        ]
        output[f"{directory}/api.ts"] = "\n".join(
            [
                _HEADER,
                'import type * as Types from "../types.js";',
                "import type { ClientOptions, RequestOptions } "
                'from "../transport/sse.js";',
                f'import {{ {", ".join(functions)} }} from "../transport/sse.js";',
                "",
                *declarations,
                f"export function {factory}(client: ClientOptions) {{",
                "  return {",
                *methods,
                "  };",
                "}",
                "",
            ]
        )
        output[f"{directory}/index.ts"] = _HEADER + 'export * from "./api.js";\n'
        exports.append(f'export type * from "./{directory}/api.js";')
    output["client.ts"] = "\n".join(
        [
            *imports,
            "",
            "export function createClient(options: ClientOptions) {",
            "  return {",
            *groups,
            "  };",
            "}",
            "",
            "export type Client = ReturnType<typeof createClient>;",
            "",
        ]
    )
    output["index.ts"] = "\n".join(exports) + "\n"
    return output
